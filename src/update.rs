/// Strict `major.minor.patch` (leading `v` tolerated) — we control the tag
/// format, so no semver machinery is pulled in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct VersionTriple {
    pub major: u64,
    pub minor: u64,
    pub patch: u64,
}

impl VersionTriple {
    pub fn parse(s: &str) -> Result<Self, String> {
        let s = s.trim().strip_prefix('v').unwrap_or(s.trim());
        let mut parts = s.split('.');
        let (Some(major), Some(minor), Some(patch), None) =
            (parts.next(), parts.next(), parts.next(), parts.next())
        else {
            return Err(format!("expected `major.minor.patch`, got {s:?}"));
        };
        let parse_num = |v: &str| {
            v.parse::<u64>()
                .map_err(|_| format!("non-numeric version component {v:?}"))
        };
        Ok(VersionTriple {
            major: parse_num(major)?,
            minor: parse_num(minor)?,
            patch: parse_num(patch)?,
        })
    }

    pub fn current() -> Self {
        // Compile-time constant; the parse is exercised by unit tests.
        VersionTriple::parse(env!("CARGO_PKG_VERSION")).expect("CARGO_PKG_VERSION is x.y.z")
    }
}

impl std::fmt::Display for VersionTriple {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}.{}.{}", self.major, self.minor, self.patch)
    }
}

/// Whether the update check should stop here and report "up to date".
///
/// `latest == current` is always up to date — `--force` exists to allow a
/// deliberate reinstall/downgrade (`latest < current`), not to announce a
/// phantom `vX → vX` update (which made `update --check --force` exit 70 on a
/// current install).
pub fn should_skip_update(latest: VersionTriple, current: VersionTriple, force: bool) -> bool {
    latest == current || (latest <= current && !force)
}

