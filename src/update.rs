#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn version_triple_parses_and_orders() {
        assert_eq!(
            VersionTriple::parse("2.10.0"),
            Ok(VersionTriple {
                major: 2,
                minor: 10,
                patch: 0
            })
        );
        assert_eq!(VersionTriple::parse("v3.0.1").unwrap().patch, 1);
        assert!(VersionTriple::parse("2.10").is_err());
        assert!(VersionTriple::parse("2.10.0.1").is_err());
        assert!(VersionTriple::parse("2.x.0").is_err());
        assert!(VersionTriple::parse(" 2.10.0 ").is_ok());

        let a = VersionTriple::parse("2.9.0").unwrap();
        let b = VersionTriple::parse("2.10.0").unwrap();
        assert!(a < b); // numeric compare, not lexicographic ("9" > "10")
        assert_eq!(b.to_string(), "2.10.0");
    }

    #[test]
    fn current_version_parses() {
        // CARGO_PKG_VERSION must always satisfy the strict triple format.
        assert_eq!(
            VersionTriple::parse(env!("CARGO_PKG_VERSION")).unwrap(),
            VersionTriple::current()
        );
    }

    #[test]
    fn target_triple_is_known_on_ci_platforms() {
        // This test binary runs on the same triples CI publishes for.
        assert!(target_triple().is_some());
    }

    #[test]
    fn manifest_parses() {
        let raw = serde_json::json!({
            "version": "2.11.0",
            "released_at": "2026-10-01T00:00:00Z",
            "notes_url": "https://example.com/notes",
            "assets": {
                "x86_64-unknown-linux-gnu": {
                    "name": "rust-hf-downloader-x86_64-unknown-linux-gnu.tar.gz",
                    "format": "tar-gz",
                    "sha256": "aa"
                },
                "x86_64-pc-windows-msvc": {
                    "name": "rust-hf-downloader-x86_64-pc-windows-msvc.zip",
                    "format": "zip",
                    "sha256": "bb"
                }
            }
        });
        let m: Manifest = serde_json::from_value(raw).unwrap();
        assert_eq!(m.version, "2.11.0");
        let lin = m.assets.get("x86_64-unknown-linux-gnu").unwrap();
        assert_eq!(lin.format, AssetFormat::TarGz);
        let win = m.assets.get("x86_64-pc-windows-msvc").unwrap();
        assert_eq!(win.format, AssetFormat::Zip);
    }

    #[test]
    fn manifest_rejects_unknown_format() {
        let raw = serde_json::json!({
            "version": "2.11.0",
            "assets": {
                "t": { "name": "n", "format": "zstd", "sha256": "aa" }
            }
        });
        assert!(serde_json::from_value::<Manifest>(raw).is_err());
    }

    #[test]
    fn base_url_strips_trailing_slash_and_honors_override() {
        // SAFETY: tests run multi-threaded but sequentially within this module.
        let key = "RHD_UPDATE_BASE";
        let prev = std::env::var_os(key);
        unsafe { std::env::set_var(key, "http://mirror.example/releases//") };
        assert_eq!(base_url(), "http://mirror.example/releases");
        match prev {
            Some(v) => unsafe { std::env::set_var(key, v) },
            None => unsafe { std::env::remove_var(key) },
        }
        assert!(!base_url().ends_with('/'));
    }
}
