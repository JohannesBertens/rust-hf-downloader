/// Extracts exactly one `rust-hf-downloader[.exe]` member from the release
/// archive into `<archive_dir>/<bin_name>` and returns its path.
pub fn extract_binary(archive: &Path, format: AssetFormat) -> Result<PathBuf, UpdateError> {
    let dest = archive
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join(BIN_NAME);

    let matches = |name: &str| {
        Path::new(name)
            .file_name()
            .map(|n| n == BIN_NAME)
            .unwrap_or(false)
    };

    let mut found = 0usize;
    match format {
        AssetFormat::TarGz => extract_tar_gz(archive, &matches, &dest, &mut found)?,
        AssetFormat::Zip => extract_zip(archive, &matches, &dest, &mut found)?,
    }

    match found {
        1 => {
            // A 0-byte member (empty regular file, or a non-file member whose
            // data read yields nothing) passes the manifest checksum and would
            // be swapped in as an empty binary.
            let len = std::fs::metadata(&dest)
                .map_err(|e| UpdateError::Archive(format!("stating {}: {e}", dest.display())))?
                .len();
            if len == 0 {
                return Err(UpdateError::Archive(format!(
                    "the `{BIN_NAME}` member extracted to 0 bytes"
                )));
            }
            Ok(dest)
        }
        0 => Err(UpdateError::Archive(format!(
            "no `{BIN_NAME}` member found"
        ))),
        n => Err(UpdateError::Archive(format!(
            "archive contains {n} `{BIN_NAME}` members (expected exactly 1)"
        ))),
    }
}

#[cfg(unix)]
fn extract_tar_gz(
    archive: &Path,
    matches: &dyn Fn(&str) -> bool,
    dest: &Path,
    found: &mut usize,
) -> Result<(), UpdateError> {
    use std::io::Write;
    let file = std::fs::File::open(archive)
        .map_err(|e| UpdateError::Archive(format!("open {}: {e}", archive.display())))?;
    let decoder = flate2::read::GzDecoder::new(file);
    let mut tar = tar::Archive::new(decoder);
    for entry in tar
        .entries()
        .map_err(|e| UpdateError::Archive(format!("reading tar: {e}")))?
    {
        let mut entry = entry.map_err(|e| UpdateError::Archive(format!("tar entry: {e}")))?;
        // Only regular files may become the staged binary: a `directory` entry
        // named `rust-hf-downloader/` matches the basename test and its data
        // read yields 0 bytes. Skipping it here means "no member found".
        if !entry.header().entry_type().is_file() {
            continue;
        }
        let path = entry
            .path()
            .map_err(|e| UpdateError::Archive(format!("tar entry path: {e}")))?
            .to_path_buf();
        let Some(name) = path.to_str() else {
            continue;
        };
        if !matches(name) {
            continue;
        }
        *found += 1;
        if *found > 1 {
            continue;
        }
        let mut out = std::fs::File::create(dest)
            .map_err(|e| UpdateError::Archive(format!("creating {}: {e}", dest.display())))?;
        let mut bytes = Vec::new();
        entry
            .read_to_end(&mut bytes)
            .map_err(|e| UpdateError::Archive(format!("reading member: {e}")))?;
        out.write_all(&bytes)
            .map_err(|e| UpdateError::Archive(format!("writing {}: {e}", dest.display())))?;
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(dest, std::fs::Permissions::from_mode(0o755))
            .map_err(|e| UpdateError::Archive(format!("chmod {}: {e}", dest.display())))?;
    }
    Ok(())
}

#[cfg(windows)]
fn extract_tar_gz(
    _archive: &Path,
    _matches: &dyn Fn(&str) -> bool,
    _dest: &Path,
    _found: &mut usize,
) -> Result<(), UpdateError> {
    // Unix assets are never served to Windows binaries (asset triples are
    // platform-mapped); unreachable by construction.
    Err(UpdateError::Archive(
        "tar.gz extraction is Unix-only".into(),
    ))
}

#[cfg(windows)]
fn extract_zip(
    archive: &Path,
    matches: &dyn Fn(&str) -> bool,
    dest: &Path,
    found: &mut usize,
) -> Result<(), UpdateError> {
    let file = std::fs::File::open(archive)
        .map_err(|e| UpdateError::Archive(format!("open {}: {e}", archive.display())))?;
    let mut zip = zip::ZipArchive::new(file)
        .map_err(|e| UpdateError::Archive(format!("reading zip: {e}")))?;
    for i in 0..zip.len() {
        let mut entry = zip
            .by_index(i)
            .map_err(|e| UpdateError::Archive(format!("zip entry {i}: {e}")))?;
        // Mirror of the tar entry-type guard: a directory member named
        // `rust-hf-downloader/` matches the basename test and extracts to
        // 0 bytes. Skipping it means "no member found". (The 0-byte guard is
        // shared in `extract_binary`.) cfg(windows): compile-blind on CI.
        if entry.is_dir() {
            continue;
        }
        let name = entry.name().to_string();
        if !matches(&name) {
            continue;
        }
        *found += 1;
        if *found > 1 {
            continue;
        }
        let mut out = std::fs::File::create(dest)
            .map_err(|e| UpdateError::Archive(format!("creating {}: {e}", dest.display())))?;
        std::io::copy(&mut entry, &mut out)
            .map_err(|e| UpdateError::Archive(format!("extracting member: {e}")))?;
    }
    Ok(())
}

#[cfg(not(windows))]
fn extract_zip(
    _archive: &Path,
    _matches: &dyn Fn(&str) -> bool,
    _dest: &Path,
    _found: &mut usize,
) -> Result<(), UpdateError> {
    // Windows assets are never served to non-Windows binaries.
    Err(UpdateError::Archive(
        "zip extraction is Windows-only".into(),
    ))
}

